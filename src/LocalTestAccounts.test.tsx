import { fireEvent, render, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import App from './App'
import { localTestAccounts } from './lib/local-test-accounts'

vi.mock('./lib/neon-auth', () => ({ neonAuth: null, neonAuthConfigured: false, getNeonAuthToken: vi.fn() }))
afterEach(() => vi.unstubAllEnvs())

describe('local participant screens', () => {
  it('keeps John and Chris on their own screens and sends administrator picks to John immediately', () => {
    vi.stubEnv('MODE', 'development')
    const administrator = render(<App />)
    const admin = within(administrator.container)
    fireEvent.click(admin.getByRole('button', { name: 'Draft' }))
    const coachScreen = render(<App testAccount={localTestAccounts['coach-john-test']} />)
    const coach = within(coachScreen.container)
    expect(coach.getByRole('button', { name: 'John Test local test profile' })).toBeTruthy()
    expect(coach.queryByRole('button', { name: 'Admin' })).toBeNull()
    expect(coach.queryByRole('button', { name: 'Back to administrator' })).toBeNull()
    expect(coach.queryByRole('combobox', { name: 'Coach team for draft pick' })).toBeNull()
    expect(coach.getByRole('combobox', { name: 'Draft division' })).toBeDisabled()
    fireEvent.click(admin.getByRole('button', { name: 'Start draft' }))
    fireEvent.change(admin.getByRole('combobox', { name: 'Select player to assign' }), { target: { value: 'draft-test-2-0' } })
    fireEvent.click(admin.getByRole('button', { name: 'Assign player to John Test' }))
    expect(coach.getByRole('region', { name: 'John Test live draft roster' })).toHaveTextContent('Alex Chen')
    expect(coach.queryByRole('button', { name: 'Select Alex Chen for John Test' })).toBeNull()
    expect(coach.getByRole('region', { name: 'Team evaluation for John Test' })).toHaveTextContent('1 / 1')
    expect(coach.getByRole('button', { name: 'Make coach pick' })).toBeDisabled()
    fireEvent.click(coach.getByRole('button', { name: 'Evaluations' }))
    expect(coach.getByRole('heading', { name: 'U10 player evaluations' })).toBeTruthy()
    expect(coachScreen.container.querySelectorAll('.batch-evaluation-table tbody tr')).toHaveLength(30)
    const evaluationNames = [...coachScreen.container.querySelectorAll('.batch-evaluation-table tbody th[scope="row"]')].map((cell) => cell.textContent)
    expect(evaluationNames[0]).toBe('Frankie Adams')
    expect(evaluationNames.at(-1)).toBe('Drew Young')
    const evaluationRows = [...coachScreen.container.querySelectorAll('.batch-evaluation-table tbody tr')]
    expect(evaluationRows.map((row) => Number(row.children[1].textContent))).toEqual(Array.from({ length: 30 }, (_, index) => index + 1))
    expect(coach.getByRole('combobox', { name: 'Evaluation division' })).toBeDisabled()
    const evaluator = coach.getByRole('combobox', { name: 'Batch evaluation coach' })
    expect(evaluator).toHaveValue('John Test')
    expect(evaluator).toBeDisabled()
    expect(within(evaluator).getAllByRole('option')).toHaveLength(1)
    expect(coach.queryByRole('checkbox', { name: 'Select head coach Cameron Scott' })).toBeNull()
    expect(coach.queryByRole('button', { name: 'Import roster' })).toBeNull()
    expect(coach.queryByRole('button', { name: 'Consolidate U10 coach evaluations' })).toBeNull()
    fireEvent.click(coach.getByRole('button', { name: 'My Team' }))
    expect(coach.getByRole('combobox', { name: 'My Team head coach' })).toBeDisabled()
    fireEvent.change(coach.getByRole('textbox', { name: 'Missing assistant coach name' }), { target: { value: 'Assistant Pat Example' } })
    fireEvent.click(coach.getByRole('button', { name: 'Add assistant to team' }))
    expect(coach.getByLabelText('Background check for Assistant Pat Example')).toHaveTextContent('Awaiting club verification')
    expect(coach.queryByRole('checkbox', { name: 'Club background check complete for Assistant Pat Example' })).toBeNull()
    fireEvent.click(admin.getByRole('button', { name: 'Admin' }))
    fireEvent.click(admin.getByRole('button', { name: 'Coaches' }))
    expect(admin.getByRole('combobox', { name: 'Assistant for John Test' })).toHaveValue('Assistant Pat Example')
    fireEvent.change(admin.getByLabelText('First practice for John Test'), { target: { value: '2026-08-15' } })
    expect(admin.getByRole('checkbox', { name: 'Club background check complete for John Test' })).toBeDisabled()
    fireEvent.change(admin.getByLabelText('Background check conducted on for John Test'), { target: { value: '2026-08-01' } })
    fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for John Test' }))
    expect(coach.getByLabelText('Background check for John Test')).toHaveTextContent('Verified complete')
    expect(coach.getByLabelText('Background check for John Test')).toHaveTextContent('Fall 2026 / Spring 2027')
    expect(coach.queryByRole('checkbox', { name: 'Club background check complete for John Test' })).toBeNull()
    fireEvent.change(admin.getByLabelText('Background check conducted on for Assistant Pat Example'), { target: { value: '2026-08-01' } })
    fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for Assistant Pat Example' }))
    expect(coach.getByLabelText('Background check for Assistant Pat Example')).toHaveTextContent('Verified complete')
    fireEvent.change(coach.getByRole('combobox', { name: 'My Team assistant coach' }), { target: { value: '' } })
    fireEvent.change(coach.getByRole('textbox', { name: 'Missing assistant coach name' }), { target: { value: 'Assistant Sam Example' } })
    fireEvent.click(coach.getByRole('button', { name: 'Add assistant to team' }))
    expect(coach.getByLabelText('Background check for Assistant Sam Example')).toHaveTextContent('Awaiting club verification')
    expect(admin.getByRole('checkbox', { name: 'Club background check complete for Assistant Sam Example' })).not.toBeChecked()
    fireEvent.change(admin.getByLabelText('Background check conducted on for Assistant Sam Example'), { target: { value: '2026-08-20' } })
    fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for Assistant Sam Example' }))
    expect(coach.getByLabelText('Background check for Assistant Sam Example')).toHaveTextContent('Completed after first practice')
    fireEvent.click(coach.getByRole('button', { name: 'Draft' }))
    expect(coach.getByRole('region', { name: 'John Test live draft roster' })).toHaveTextContent('Alex Chen')
    const refereeScreen = render(<App testAccount={localTestAccounts['ref-chris-james']} />)
    const referee = within(refereeScreen.container)
    expect(referee.getByText('Chris James')).toBeTruthy()
    expect(referee.getByRole('heading', { name: 'RefHome' })).toBeTruthy()
    expect(refereeScreen.container.querySelector('.sidebar')).toBeNull()
    expect(refereeScreen.container.querySelector('.topbar')).toBeNull()
    expect(referee.queryByRole('button', { name: 'Admin' })).toBeNull()
    expect(referee.queryByRole('button', { name: 'Draft' })).toBeNull()
    fireEvent.click(referee.getByRole('button', { name: /GameCard/ }))
    expect(referee.getByRole('heading', { name: 'GameCard' })).toBeTruthy()
  }, 60_000)
})
