import { act, fireEvent, render, screen, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { DraftWalkthrough } from './DraftWalkthrough'

afterEach(() => vi.useRealTimers())
const coaches = ['Avery Hill', 'Morgan Reed', 'Sam Patel', 'Casey Young', 'Riley Stone']
const seat = (name: string) => screen.getByRole('region', { name: `Coach ${name} view` })
const confirm = (name: string) => within(seat(name)).getByRole('button', { name: /^Confirm pick/ })
const activity = () => screen.getByRole('region', { name: 'Shared draft activity' })
const record = () => screen.getByRole('button', { name: /^Record pick for/ })
const choose = (id: number) => fireEvent.change(screen.getByRole('combobox', { name: 'Player to record for current coach' }), { target: { value: `draft-player-${id}` } })

describe('Five-coach 40-player draft walkthrough', () => {
  it('returns from a coach view and advances their preference board when another coach takes a choice', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Coach Morgan Reed' }))
    fireEvent.click(screen.getByRole('button', { name: 'Prioritize Jordan Lee for Morgan Reed' }))
    fireEvent.click(screen.getByRole('button', { name: 'Prioritize Casey Rivera for Morgan Reed' }))
    fireEvent.click(screen.getByRole('button', { name: 'Back to administrator' }))
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    choose(0); fireEvent.click(record())
    fireEvent.click(screen.getByRole('button', { name: 'Coach Morgan Reed' }))
    const board = screen.getByRole('region', { name: 'Suggested draft board for Morgan Reed' })
    expect(within(board).getAllByRole('listitem')[0]).toHaveTextContent('Casey Rivera')
    expect(within(board).queryByRole('button', { name: 'Select Jordan Lee for Morgan Reed' })).toBeNull()
    expect(within(seat('Morgan Reed')).getByRole('button', { name: 'Select Casey Rivera for Morgan Reed' })).toHaveAttribute('aria-pressed', 'true')
    fireEvent.click(screen.getByRole('button', { name: 'Back to administrator' }))
    choose(1); fireEvent.click(record())
    fireEvent.click(screen.getByRole('button', { name: 'Coach Morgan Reed' }))
    expect(seat('Morgan Reed').querySelector('.draft-seat-roster')).toHaveTextContent('Casey Rivera')
  })

  it('records the administrator pick for the current coach and updates all five views', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    expect(screen.getByRole('region', { name: 'Shared player board' }).querySelectorAll('tbody tr')).toHaveLength(40)
    expect(record()).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    choose(0); fireEvent.click(record())
    expect(within(activity()).getByText('Jordan Lee')).toBeTruthy()
    expect(record()).toHaveTextContent('Gold Eagles')
    expect(record()).toBeDisabled()
    for (const name of coaches) {
      expect(seat(name)).toHaveTextContent('Jordan Lee → Blue Comets')
      expect(within(seat(name)).queryByRole('button', { name: `Select Jordan Lee for ${name}` })).toBeNull()
    }
    const row = within(screen.getByRole('region', { name: 'Shared player board' })).getByRole('rowheader', { name: '#22 Jordan Lee' }).closest('tr')!
    expect(row).toHaveClass('draft-public-taken')
    expect(row).toHaveTextContent('Blue Comets · Avery Hill')
    expect(row.lastElementChild).toHaveTextContent('1')
    expect(within(seat('Morgan Reed')).getByRole('status')).toHaveTextContent('Your turn')
  })
  it('enforces coach-entered turns across all five coaches', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.change(screen.getByRole('combobox', { name: 'Pick entry method' }), { target: { value: 'coach' } })
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    fireEvent.click(within(seat('Morgan Reed')).getByRole('button', { name: 'Select Casey Rivera for Morgan Reed' }))
    expect(confirm('Morgan Reed')).toBeDisabled()
    for (const name of [...coaches, ...[...coaches].reverse(), coaches[0]]) {
      fireEvent.click(within(seat(name)).getAllByRole('button', { name: /^Select / })[0])
      expect(confirm(name)).toBeEnabled()
      fireEvent.click(confirm(name))
    }
    expect(within(activity()).getAllByRole('listitem')).toHaveLength(11)
    expect(within(seat('Morgan Reed')).getByRole('status')).toHaveTextContent('Your turn')
  })
  it('keeps planning separate in individual coach and administrator views', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Coach Avery Hill' }))
    fireEvent.change(screen.getByRole('textbox', { name: 'Private notes for Avery Hill' }), { target: { value: 'Prioritize passing.' } })
    expect(screen.queryByRole('region', { name: 'Administrator pick entry' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Coach Morgan Reed' }))
    expect(screen.queryByDisplayValue('Prioritize passing.')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Administrator' }))
    expect(screen.queryByRole('textbox')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Coach Avery Hill' }))
    expect(screen.getByRole('textbox', { name: 'Private notes for Avery Hill' })).toHaveValue('Prioritize passing.')
  })
  it('pauses the clock and blocks picks after expiry without choosing automatically', () => {
    vi.useFakeTimers()
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    act(() => vi.advanceTimersByTime(5000))
    expect(screen.getByLabelText('Pick clock')).toHaveTextContent('1:25')
    fireEvent.click(screen.getByRole('button', { name: 'Pause draft' }))
    act(() => vi.advanceTimersByTime(10000))
    expect(screen.getByLabelText('Pick clock')).toHaveTextContent('1:25')
    fireEvent.click(screen.getByRole('button', { name: 'Resume draft' }))
    choose(0)
    act(() => vi.advanceTimersByTime(85000))
    expect(record()).toBeDisabled()
    expect(within(activity()).queryByRole('listitem')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Reset pick clock' }))
    expect(record()).toBeEnabled()
  })
  it('undoes only while paused and restores the player and turn', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    choose(0); fireEvent.click(record())
    expect(screen.getByRole('button', { name: 'Undo last pick' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Pause draft' }))
    fireEvent.click(screen.getByRole('button', { name: 'Undo last pick' }))
    for (const name of coaches) expect(within(seat(name)).getByRole('button', { name: `Select Jordan Lee for ${name}` })).toBeTruthy()
    expect(within(activity()).queryByRole('listitem')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Resume draft' }))
    expect(record()).toHaveTextContent('Blue Comets')
  })
  it('runs forty unique picks into five eight-player rosters', () => {
    render(<DraftWalkthrough onClose={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    for (let round = 0; round < 8; round += 1) fireEvent.click(screen.getByRole('button', { name: 'Run next 5 picks' }))
    expect(document.querySelectorAll('.draft-team-progress strong')).toHaveLength(5)
    for (const count of document.querySelectorAll('.draft-team-progress strong')) expect(count).toHaveTextContent('8 / 8')
    for (const name of coaches) expect(seat(name).querySelector('.draft-seat-roster h3')).toHaveTextContent('8 / 8')
    expect(within(activity()).getAllByRole('listitem')).toHaveLength(40)
    const rows = screen.getByRole('region', { name: 'Shared player board' }).querySelectorAll('tbody tr')
    const openingTurns = [...coaches, ...[...coaches].reverse(), coaches[0]]
    openingTurns.forEach((coach, index) => {
      const row = [...rows].find((entry) => entry.lastElementChild?.textContent === String(index + 1))!
      expect(row.children[2]).toHaveTextContent(coach)
    })
    expect(rows[0]).toHaveTextContent('Oakley Adams')
    expect([...rows].every((row) => row.classList.contains('draft-public-taken'))).toBe(true)
    expect(new Set([...rows].map((row) => row.lastElementChild?.textContent)).size).toBe(40)
    expect(record()).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Run next 5 picks' })).toBeDisabled()
  })
  it('sets coach order before starting and returns to the workspace', () => {
    const close = vi.fn()
    render(<DraftWalkthrough onClose={close} />)
    fireEvent.click(screen.getByRole('button', { name: 'Move Sam Patel earlier' }))
    fireEvent.click(screen.getByRole('button', { name: 'Move Sam Patel earlier' }))
    fireEvent.click(screen.getByRole('button', { name: 'Start draft' }))
    expect(record()).toHaveTextContent('Green Strikers')
    expect(screen.getByRole('button', { name: 'Move Sam Patel later' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Return to draft workspace' }))
    expect(close).toHaveBeenCalledOnce()
  })
})
