import { fireEvent, render, within } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import App from './App'
import { localTestAccounts } from './lib/local-test-accounts'

vi.mock('./lib/neon-auth', () => ({ neonAuth: null, neonAuthConfigured: false, getNeonAuthToken: vi.fn() }))
afterEach(() => { vi.unstubAllEnvs(); vi.useRealTimers() })

it('shares Admin-generated fixtures and cancellations with coach and referee screens and retains schedule parameters', () => {
  vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2030-05-31T12:00:00Z'))
  vi.stubEnv('MODE', 'development')
  const adminScreen = render(<App />)
  const admin = within(adminScreen.container)
  fireEvent.click(admin.getByRole('button', { name: 'Admin' }))
  fireEvent.click(admin.getByRole('button', { name: 'Referees' }))
  fireEvent.click(admin.getByRole('button', { name: 'Edit referee Chris James' }))
  fireEvent.change(admin.getByLabelText('Referee phone'), { target: { value: '555-010-1234' } })
  fireEvent.change(admin.getByLabelText('Referee preferred contact method'), { target: { value: 'text' } })
  fireEvent.click(admin.getByRole('checkbox', { name: 'U10' }))
  fireEvent.click(admin.getByRole('button', { name: 'Add availability window' }))
  fireEvent.change(admin.getByLabelText('Availability first date 1'), { target: { value: '2030-06-01' } })
  fireEvent.change(admin.getByLabelText('Availability last date 1'), { target: { value: '2030-08-31' } })
  fireEvent.change(admin.getByLabelText('Referee background check fall year'), { target: { value: '2029' } })
  fireEvent.change(admin.getByLabelText('Referee first practice or duty date'), { target: { value: '2030-06-01' } })
  fireEvent.change(admin.getByLabelText('Background check conducted on for Chris James'), { target: { value: '2029-08-01' } })
  fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for Chris James' }))
  fireEvent.click(admin.getByRole('button', { name: 'Save referee' }))
  fireEvent.click(admin.getByRole('button', { name: 'Schedule' }))
  fireEvent.click(admin.getByRole('button',{name:'Edit scheduling settings'}))
  fireEvent.change(admin.getByLabelText('First match date'), { target: { value: '2030-06-01' } })
  fireEvent.change(admin.getByLabelText('Last match date'), { target: { value: '2030-08-31' } })
  fireEvent.click(admin.getByRole('button', { name: 'Build schedule preview' }))
  fireEvent.click(admin.getByRole('button', { name: 'Apply schedule' }))
  expect(adminScreen.container.querySelectorAll('.schedule-table tbody tr')).toHaveLength(10)
  fireEvent.click(admin.getByRole('button', { name: 'Season' }))
  fireEvent.click(admin.getByRole('button', { name: 'Schedule' }))
  fireEvent.click(admin.getByRole('button',{name:'Edit scheduling settings'}))
  expect(admin.getByLabelText('First match date')).toHaveValue('2030-06-01')

  const coachScreen = render(<App testAccount={localTestAccounts['coach-john-test']} />)
  const coach = within(coachScreen.container)
  fireEvent.click(coach.getByRole('button', { name: 'My Team' }))
  expect(coach.getByRole('region', { name: 'My Team matches' })).toHaveTextContent('scheduled')

  const johnRow = [...adminScreen.container.querySelectorAll('.schedule-table tbody tr')].find((row) => row.children[2].textContent?.includes('John Test'))!
  const date = johnRow.children[0].textContent!.slice(0, 10)
  const refereeScreen = render(<App testAccount={localTestAccounts['ref-chris-james']} />)
  const referee = within(refereeScreen.container)
  fireEvent.click(referee.getByRole('button', { name: /GameCard/ }))
  fireEvent.change(referee.getByLabelText('Referee score date'), { target: { value: date } })
  const gameButtons = refereeScreen.container.querySelectorAll('.score-game-choice')
  const initialCount = gameButtons.length
  expect(initialCount).toBeGreaterThan(0)
  fireEvent.click(gameButtons[0])
  expect(referee.getByText(/U10 · Field .*55 minutes including breaks/)).toBeTruthy()
  expect(referee.getByLabelText('Referee name')).toHaveValue('Chris James')
  const manageLabel = within(johnRow as HTMLElement).getByRole('button', { name: /Manage match/ }).getAttribute('aria-label')!
  fireEvent.click(admin.getByRole('button', { name: 'Referees' }))
  fireEvent.click(admin.getByRole('button', { name: 'Edit referee Chris James' }))
  fireEvent.change(admin.getByLabelText('Referee background check fall year'), { target: { value: '2029' } })
  fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for Chris James' }))
  fireEvent.click(admin.getByRole('button', { name: 'Save referee' }))
  expect(referee.getByRole('alert')).toHaveTextContent('current verified background check')
  expect(referee.getByRole('button', { name: 'Increase home score' })).toBeDisabled()
  fireEvent.click(admin.getByRole('checkbox', { name: 'Club background check complete for Chris James' }))
  fireEvent.click(admin.getByRole('button', { name: 'Save referee' }))
  expect(referee.getByRole('button', { name: 'Increase home score' })).toBeEnabled()
  fireEvent.click(admin.getByRole('button', { name: 'Schedule' }))
  fireEvent.click(admin.getByRole('button',{name:'Edit scheduling settings'}))

  fireEvent.click(admin.getByRole('button', { name: manageLabel }))
  fireEvent.click(admin.getByRole('checkbox', { name: /Close this date for U10/ }))
  fireEvent.click(admin.getByRole('button', { name: 'Cancel match' }))
  expect(coach.getByRole('region', { name: 'My Team matches' })).toHaveTextContent('cancelled')
  expect(coach.getByRole('region', { name: 'My Team matches' })).toHaveTextContent('Weather')
  expect(refereeScreen.container.querySelectorAll('.score-game-choice')).toHaveLength(initialCount - 1)
}, 60_000)

it('configures U6 teams and schedules them only on fields 3, 4 or 5 with PDSA timing', () => {
  const view = render(<App />)
  const admin = within(view.container)
  fireEvent.click(admin.getByRole('button', { name: 'Admin' }))
  fireEvent.click(admin.getByRole('button', { name: 'U6 Teams' }))
  fireEvent.change(admin.getByRole('spinbutton', {name:'Number of U6 teams'}), { target: { value: '2' } })
  fireEvent.click(admin.getByRole('checkbox', { name: 'Avery Hill' }))
  fireEvent.click(admin.getByRole('checkbox', { name: 'Morgan Reed' }))
  fireEvent.click(admin.getByRole('button', { name: 'Schedule' }))
  fireEvent.click(admin.getByRole('button',{name:'Edit scheduling settings'}))
  fireEvent.click(admin.getByRole('tab', { name: 'U6' }))
  expect(admin.getByText('U6: 41 minutes including breaks')).toBeTruthy()
  for (const field of ['3', '4', '5']) expect(admin.getByRole('checkbox', { name: `Use field ${field}` })).toBeChecked()
  expect(admin.queryByRole('checkbox', { name: 'Use field 8' })).toBeNull()
  fireEvent.change(admin.getByLabelText('First match date'), { target: { value: '2030-06-01' } })
  fireEvent.change(admin.getByLabelText('Last match date'), { target: { value: '2030-08-31' } })
  fireEvent.click(admin.getByRole('button', { name: 'Build schedule preview' }))
  fireEvent.click(admin.getByRole('button', { name: 'Apply schedule' }))
  const rows = view.container.querySelectorAll('.schedule-table tbody tr')
  expect(rows).toHaveLength(1)
  expect(rows[0].children[1]).toHaveTextContent('3')
}, 30_000)
